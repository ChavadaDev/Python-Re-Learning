# Assingment Operators In Python:

a = 2 
print(a) # Output: 2

a += 2 # a = a + 2
print(a) # Output: 4

a -= 3 # a = a - 3
print(a) # Output: 1

a *= 2 # a = a * 2
print(a) # Output: 2

a /= 1 # a = a / 1
print(a) # Output: 2.0

a %= 2 # a = a % 2
print(a) # Output: 0.0

a **= 2 # a = a ** 2
print(a) # Output: 0.0

a //= 2 # a = a // 2
print(a) # Output: 0.0
