# Operators In Python: 
# 1. Arithmetic Operators: +, -, *, /, %, **, //
# 2. Comparison Operators: ==, !=, >, <, >=, <=
# 3. Assignment Operators: =, +=, -=, *=, /=, %=, **=, //=
# 4. Logical Operators: and, or, not
# 5. Bitwise Operators: &, |, ^, ~, <<, >>
# 6. Membership Operators: in, not in
# 7. Identity Operators: is, is not


# 1. Arithmetic Operators:
a = 33
b = 10
print("Addition: var a + var b =", a + b) # Addition
print("Subtraction: var a - var b =", a - b) # Subtraction
print("Multiplication: var a * var b =", a * b) # Multiplication
print("Division: var a / var b =", a / b) # Division
print("Modulus: var a % var b =", a % b) # Modulus
print("Exponentiation: var a ** var b =", a ** b) # Exponentiation
print("Floor Division: var a // var b =", a // b) # Floor Division  


# 2. Comparison Operators:
a = 33
b = 10
print("Is a equal to b? :", a == b) # Equal to (will return True if both the operands are equal, otherwise it will return False)